#!/usr/bin/env python3
"""
Сниппеты (title + description) страниц под реальные запросы из Вебмастера.

Зачем: срез запросов за 15.07–14.08.2026 показал типичную картину «показы
есть, кликов нет» — 2 455 показов и 173 клика. Самые обидные строки:
«стоматолог реутов» 155 показов / 0 кликов, «имплантация зубов в реутове»
133 / 0, «протезирование зубов в реутове» 123 / 1. Позиции 6–10, то есть
сайт в выдаче, но выбирают не его.

Что здесь исправлено:
- в title добавлены формулировки, которыми люди ищут: «стоматолог»
  (а не только «стоматология»), «Новокосино», «лечение зубов» рядом с
  «кариесом»;
- в title вынесена цена — на позициях ниже топ-3 цифра в заголовке
  заметно поднимает CTR;
- описания укорочены до ~150–170 символов: раньше были 200–230 и
  обрывались на полуслове прямо в выдаче.

Цены и факты — только те, что уже есть на самих страницах, ничего
нового не придумано.

Идемпотентно: повторный запуск ничего не меняет.

  python3 scripts/seo-snippets.py [--check]
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

PAGES = {
    'index.html': (
        'Стоматология в Реутове — стоматолог у м. Новокосино | Ангел-Дент',
        'Семейная стоматология «Ангел-Дент»: Реутов, ул. Победы, 22 — 10 минут от '
        'м. Новокосино. Ежедневно 10:00–20:00, с острой болью стараемся принять в день обращения.'),
    'services/detskaya.html': (
        'Детская стоматология в Реутове и Новокосино — с 2 лет | Ангел-Дент',
        'Детский стоматолог в Реутове: лечение молочного зуба от 1 500 ₽, цветные пломбы '
        'Twinky Star, герметизация фиссур. Принимаем с 2 лет, 10 минут от м. Новокосино.'),
    'services/implantaciya.html': (
        'Имплантация зубов в Реутове — имплант от 28 000 ₽ | Ангел-Дент',
        'Имплантация в Реутове: Osstem от 28 000 ₽, под ключ с коронкой от 45 000 ₽, '
        'Straumann, All-on-4, одномоментная. Гарантия до 10 лет, КТ и план бесплатно.'),
    'services/protezirovanie.html': (
        'Протезирование зубов в Реутове — коронка от 12 000 ₽ | Ангел-Дент',
        'Протезирование в Реутове: металлокерамика от 12 000 ₽, цирконий от 22 000 ₽, '
        'E-max, съёмные протезы. Цифровые слепки без слепочной массы, гарантия по договору.'),
    'services/terapiya.html': (
        'Лечение зубов в Реутове — кариес от 5 500 ₽ за визит | Ангел-Дент',
        'Лечение кариеса в Реутове от 5 500 ₽ за один визит: анестезия и пломба в цене. '
        'Каналы под микроскопом Carl Zeiss, гарантия 2 года по договору.'),
    'services/gigiena.html': (
        'Чистка и отбеливание зубов в Реутове — от 5 000 ₽ | Ангел-Дент',
        'Комплексная чистка 5 000 ₽: ультразвук, Air Flow и полировка. Отбеливание '
        'Amazing White — 17 500 ₽ вместо 25 000 ₽ за обе челюсти. Реутов, м. Новокосино.'),
}


def main() -> int:
    check = '--check' in sys.argv
    changed = []
    for rel, (title, desc) in PAGES.items():
        p = ROOT / rel
        s = p.read_text(encoding='utf-8')
        out = re.sub(r'<title>.*?</title>', f'<title>{title}</title>', s, count=1, flags=re.S)
        out = re.sub(r'(<meta name="description" content=")(.*?)(")',
                     lambda m: m.group(1) + desc + m.group(3), out, count=1, flags=re.S)
        if out != s:
            changed.append(rel)
            if not check:
                p.write_text(out, encoding='utf-8')
        print(f'  {"·" if out == s else "✓"} {rel:34} title {len(title):3}, description {len(desc):3}')
    print(f'{"нужно обновить" if check else "обновлено"}: {len(changed)} страниц')
    return 1 if (check and changed) else 0


if __name__ == '__main__':
    sys.exit(main())
