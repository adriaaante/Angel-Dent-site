def next_no(cfg, counter):
    """Выдать следующий номер из сквозного счётчика и сдвинуть его."""
    n = cfg["counters"][counter]
    cfg["counters"][counter] = n + 1
    return n


def log_doc(cfg, kind, no, doc_date, amount, title, note=""):
    """Записать документ в реестр (без дублей по kind+no)."""
    entry = {"kind": kind, "no": str(no), "date": doc_date,
             "amount": amount, "title": title, "note": note}
    docs = cfg.setdefault("documents", [])
    for i, d in enumerate(docs):
        if d["kind"] == kind and d["no"] == str(no):
            docs[i] = entry
            return entry
    docs.append(entry)
    docs.sort(key=lambda d: (d["date"], d["kind"], d["no"]))
    return entry


