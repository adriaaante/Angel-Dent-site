def build_reconciliation(cfg):
    ex, cu, c = cfg["executor"], cfg["customer"], cfg["contract"]
    payments = cfg.get("past_payments", [])
    doc = new_doc()

    heading(doc, "АКТ СВЕРКИ")
    heading(doc, "взаимных расчётов", size=12)
    period_to = date_ru(c["date"], quoted=False)
    period_from = date_ru(c["retro_from"], quoted=False)
    heading(doc, f"за период с {period_from} по {period_to}", size=11)
    para(doc)

    para(doc, f"Между: {requisites_line(ex, 'executor')}.", align="just", space_after=3)
    para(doc, f"и: {requisites_line(cu, 'customer')}.", align="just")
    para(doc, "Предмет: услуги по продвижению сайтов "
              f"{sites_sentence(cfg)}.", align="just")
    para(doc)

    rows = [["№", "Дата", "Документ / основание", "Оказано услуг, руб.", "Оплачено, руб."]]
    total_serv = total_paid = 0.0
    if payments:
        for i, p in enumerate(payments, 1):
            rows.append([i, date_dots(p["date"]), p["basis"],
                         money(p["services"]) if p.get("services") else "—",
                         money(p["paid"]) if p.get("paid") else "—"])
            total_serv += p.get("services") or 0
            total_paid += p.get("paid") or 0
    else:
        for i in range(1, 13):
            rows.append([i, BLANK[:10], BLANK, BLANK[:10], BLANK[:10]])
    rows.append(["", "", "ИТОГО",
                 money(total_serv) if payments else BLANK[:10],
                 money(total_paid) if payments else BLANK[:10]])
    table(doc, rows, widths=[1.0, 2.6, 7.2, 3.4, 3.4],
          align_cols=["c", "c", "l", "r", "r"])

    para(doc)
    balance = total_serv - total_paid
    if payments:
        if abs(balance) < 0.005:
            verdict = ("По состоянию на дату составления настоящего акта задолженность "
                       "Сторон друг перед другом отсутствует.")
        elif balance > 0:
            verdict = (f"По состоянию на дату составления настоящего акта задолженность "
                       f"Заказчика перед Исполнителем составляет {money(balance)} руб. "
                       f"({rub_words(balance)}).")
        else:
            verdict = (f"По состоянию на дату составления настоящего акта задолженность "
                       f"Исполнителя перед Заказчиком составляет {money(-balance)} руб. "
                       f"({rub_words(-balance)}).")
    else:
        verdict = ("По состоянию на дату составления настоящего акта задолженность Сторон "
                   f"друг перед другом составляет {BLANK} руб.")
    para(doc, verdict, align="just")
    para(doc, "Стороны подтверждают, что услуги в указанном периоде фактически оказаны "
              "Исполнителем и приняты Заказчиком, оплата произведена в полном объёме, "
              "претензий по объёму, качеству, срокам оказания услуг и расчётам Стороны "
              "друг к другу не имеют.", align="just")
    para(doc, "Настоящий акт составлен в двух экземплярах, имеющих равную юридическую силу, "
              "по одному для каждой из Сторон.", align="just")
    para(doc)

    sign_block(doc, cfg)
    return save(doc, "Акт сверки взаимных расчётов.docx")


