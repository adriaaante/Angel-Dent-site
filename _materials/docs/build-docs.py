_ONES_M = ["", "один", "два", "три", "четыре", "пять", "шесть", "семь", "восемь", "девять"]
_ONES_F = ["", "одна", "две", "три", "четыре", "пять", "шесть", "семь", "восемь", "девять"]
_TEENS = ["десять", "одиннадцать", "двенадцать", "тринадцать", "четырнадцать",
          "пятнадцать", "шестнадцать", "семнадцать", "восемнадцать", "девятнадцать"]
_TENS = ["", "", "двадцать", "тридцать", "сорок", "пятьдесят",
         "шестьдесят", "семьдесят", "восемьдесят", "девяносто"]
_HUNDREDS = ["", "сто", "двести", "триста", "четыреста", "пятьсот",
             "шестьсот", "семьсот", "восемьсот", "девятьсот"]


def _plural(n, forms):
    """forms = (1 рубль, 2 рубля, 5 рублей)"""
    n = abs(n) % 100
    if 11 <= n <= 19:
        return forms[2]
    n %= 10
    if n == 1:
        return forms[0]
    if 2 <= n <= 4:
        return forms[1]
    return forms[2]


def _triple_words(n, female):
    """Число 0..999 прописью."""
    out = []
    if n >= 100:
        out.append(_HUNDREDS[n // 100])
        n %= 100
    if 10 <= n <= 19:
        out.append(_TEENS[n - 10])
    else:
        if n >= 20:
            out.append(_TENS[n // 10])
            n %= 10
        if n:
            out.append((_ONES_F if female else _ONES_M)[n])
    return [w for w in out if w]


def rub_words(amount):
    """123456.5 -> 'Сто двадцать три тысячи четыреста пятьдесят шесть рублей 50 копеек'"""
    rub = int(amount)
    kop = int(round((amount - rub) * 100))
    if kop == 100:  # защита от 1.999 -> 2 руб. 100 коп.
        rub, kop = rub + 1, 0

    if rub == 0:
        words = ["ноль"]
    else:
        words = []
        groups = [
            (10 ** 9, True, ("миллиард", "миллиарда", "миллиардов"), False),
            (10 ** 6, True, ("миллион", "миллиона", "миллионов"), False),
            (10 ** 3, True, ("тысяча", "тысячи", "тысяч"), True),
        ]
        rest = rub
        for base, _, forms, female in groups:
            part, rest = divmod(rest, base)
            if part:
                words += _triple_words(part, female) + [_plural(part, forms)]
        if rest:
            words += _triple_words(rest, False)

    text = " ".join(words)
    text = text[:1].upper() + text[1:]
    return (f"{text} {_plural(rub, ('рубль', 'рубля', 'рублей'))} "
            f"{kop:02d} {_plural(kop, ('копейка', 'копейки', 'копеек'))}")


def money(amount):
    """90000 -> '90 000,00'"""
    return f"{amount:,.2f}".replace(",", " ").replace(".", ",")


def date_ru(iso, quoted=True):
    """'2026-07-31' -> '«31» июля 2026 г.'"""
    d = datetime.strptime(iso, "%Y-%m-%d").date()
    day = f"«{d.day:02d}»" if quoted else f"{d.day:02d}"
    return f"{day} {MONTHS_GEN[d.month - 1]} {d.year} г."


def date_dots(iso):
    """'2026-07-31' -> '31.07.2026'"""
    d = datetime.strptime(iso, "%Y-%m-%d").date()
    return d.strftime("%d.%m.%Y")


