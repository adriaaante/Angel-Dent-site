def month_to_iso(label):
    """'август 2026' -> ('2026-08-01', последний день) — для подписи периода."""
    m = re.match(r"([а-яё]+)\s+(\d{4})", label.strip().lower())
    if not m:
        return None
    names = ["январ", "феврал", "март", "апрел", "ма", "июн",
             "июл", "август", "сентябр", "октябр", "ноябр", "декабр"]
    for i, n in enumerate(names, 1):
        if m.group(1).startswith(n):
            return i, int(m.group(2))
    return None


