def _esc(s):
    return (s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;"))


def _para_html(p):
    align = {1: "center", 2: "right", 3: "justify"}.get(
        int(p.alignment) if p.alignment is not None else 0, "left")
    inner = ""
    for r in p.runs:
        txt = _esc(r.text).replace("\n", "<br>")
        if r.bold:
            txt = f"<b>{txt}</b>"
        if r.italic:
            txt = f"<i>{txt}</i>"
        inner += txt
    attr = "" if align == "left" else f' style="text-align:{align}"'
    return f"<p{attr}>{inner or '&nbsp;'}</p>"


def _table_html(t):
    out = ['<table border="1" cellspacing="0" cellpadding="4" '
           'style="border-collapse:collapse;width:100%">']
    for row in t.rows:
        out.append("<tr>")
        for cell in row.cells:
            body = "".join(_para_html(p) for p in cell.paragraphs)
            out.append(f"<td>{body}</td>")
        out.append("</tr>")
    out.append("</table>")
    return "".join(out)


def doc_to_html(doc, title):
    """Тот же документ в HTML — Google Drive конвертирует его в Google Doc.

    Бинарный .docx через MCP Drive не проходит (inline base64 обрезается),
    поэтому в Drive уезжает HTML-двойник, а .docx остаётся для подписи.
    """
    body, tables, paras = [], iter(doc.tables), iter(doc.paragraphs)
    for child in doc.element.body:
        tag = child.tag.split("}")[-1]
        if tag == "p":
            body.append(_para_html(next(paras)))
        elif tag == "tbl":
            body.append(_table_html(next(tables)))
    return ('<html><head><meta charset="utf-8"><title>' + _esc(title) +
            '</title></head><body style="font-family:\'Times New Roman\',serif;'
            'font-size:11pt">' + "".join(body) + "</body></html>")


def save(doc, name):
    OUT.mkdir(exist_ok=True)
    path = OUT / name
    doc.save(path)
    html_path = path.with_suffix(".html")
    html_path.write_text(doc_to_html(doc, path.stem), encoding="utf-8")
    print(f"  ✓ {path.relative_to(ROOT)}")
    return path


