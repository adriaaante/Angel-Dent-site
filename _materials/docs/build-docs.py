def new_doc():
    doc = Document()
    st = doc.styles["Normal"]
    st.font.name = "Times New Roman"
    st.font.size = Pt(11)
    st.element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    pf = st.paragraph_format
    pf.space_after = Pt(6)
    pf.line_spacing = 1.0
    for s in doc.sections:
        s.left_margin = s.right_margin = Cm(2)
        s.top_margin = s.bottom_margin = Cm(1.5)
    return doc


def para(doc, text="", bold=False, align="left", size=None, italic=False, space_after=None):
    p = doc.add_paragraph()
    p.alignment = {
        "left": WD_ALIGN_PARAGRAPH.LEFT,
        "center": WD_ALIGN_PARAGRAPH.CENTER,
        "right": WD_ALIGN_PARAGRAPH.RIGHT,
        "just": WD_ALIGN_PARAGRAPH.JUSTIFY,
    }[align]
    if space_after is not None:
        p.paragraph_format.space_after = Pt(space_after)
    if text:
        r = p.add_run(text)
        r.bold = bold
        r.italic = italic
        if size:
            r.font.size = Pt(size)
    return p


def heading(doc, text, size=14):
    para(doc, text, bold=True, align="center", size=size, space_after=2)


def fix_layout(t, widths_cm):
    """Жёсткая раскладка таблицы: tblGrid + ширина каждой ячейки.

    python-docx выставляет только tcW у ячеек, а tblGrid оставляет с
    равными колонками. Word это прощает, но Google Docs и LibreOffice
    читают именно tblGrid — и таблица разъезжалась: колонка «№» шириной
    с колонку описания. Владелец заметил это на счёте 15.08.2026.
    """
    tbl = t._tbl
    tblPr = tbl.tblPr
    layout = tblPr.find(qn("w:tblLayout"))
    if layout is None:
        layout = tblPr.makeelement(qn("w:tblLayout"), {})
        # схема tblPr требует строгий порядок детей: tblLayout должен
        # стоять ДО tblLook, иначе LibreOffice/Google Docs не открывают файл
        look = tblPr.find(qn("w:tblLook"))
        if look is not None:
            look.addprevious(layout)
        else:
            tblPr.append(layout)
    layout.set(qn("w:type"), "fixed")
    grid = tbl.tblGrid
    for gc in list(grid):
        grid.remove(gc)
    for w in widths_cm:
        gc = grid.makeelement(qn("w:gridCol"), {})
        gc.set(qn("w:w"), str(int(w * 567)))
        grid.append(gc)
    for row in t.rows:
        for cell, w in zip(row.cells, widths_cm):
            cell.width = Cm(w)


def table(doc, rows, widths=None, header=True, align_cols=None, font=10):
    t = doc.add_table(rows=0, cols=len(rows[0]))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, row in enumerate(rows):
        cells = t.add_row().cells
        for j, val in enumerate(row):
            cell = cells[j]
            cell.text = ""
            p = cell.paragraphs[0]
            p.paragraph_format.space_after = Pt(2)
            if align_cols:
                p.alignment = {
                    "l": WD_ALIGN_PARAGRAPH.LEFT,
                    "c": WD_ALIGN_PARAGRAPH.CENTER,
                    "r": WD_ALIGN_PARAGRAPH.RIGHT,
                }[align_cols[j]]
            r = p.add_run(str(val))
            r.font.size = Pt(font)
            r.bold = header and i == 0
    if widths:
        fix_layout(t, widths)
    return t


def sign_block(doc, cfg, customer_signs=True, stamp=True):
    """Двухколоночная плашка с реквизитами и подписями."""
    ex, cu = cfg["executor"], cfg["customer"]
    left = [
        "ИСПОЛНИТЕЛЬ:",
        ex["short"],
        f"ИНН {ex['inn']}",
        f"ОГРНИП {ex['ogrnip']}",
        ex["address"],
        f"Р/с {ex['account']}",
        f"{ex['bank']}, БИК {ex['bic']}",
        f"К/с {ex['corr_account']}",
        f"тел. {ex['phone']}",
        f"e-mail: {ex['email']}",
        "",
        f"_______________ / {ex['sign_name']} /",
    ]
    right = [
        "ЗАКАЗЧИК:",
        cu["short"],
        f"ИНН {cu['inn']}, КПП {cu['kpp']}",
        f"ОГРН {cu['ogrn']}",
        cu["address"],
        f"Р/с {cu.get('account') or BLANK}",
        f"{cu.get('bank') or BLANK}, БИК {cu.get('bic') or BLANK}",
        f"К/с {cu.get('corr_account') or BLANK}",
        f"тел. {cu.get('phone') or BLANK}",
        "",
        cu["signatory_title"],
        f"_______________ / {cu['sign_name']} /",
    ]
    if stamp:
        # У ИП печати нет (владелец, 15.08.2026) — пустой оттиск «М.П.» в
        # документе только выглядел бы незаполненным полем. Закон печати
        # от ИП и не требует: с 2015 г. она не обязательна и для ООО, но у
        # клиники она есть, поэтому справа «М.П.» остаётся.
        if cfg["executor"].get("has_stamp"):
            left.append("М.П.")
        right.append("М.П.")
    if not customer_signs:
        right = right[:-2] + [""]

    t = doc.add_table(rows=1, cols=2)
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for cell, lines in zip(t.rows[0].cells, (left, right)):
        cell.text = ""
        cell.width = Cm(8.5)
        for k, line in enumerate(lines):
            p = cell.paragraphs[0] if k == 0 else cell.add_paragraph()
            p.paragraph_format.space_after = Pt(0)
            r = p.add_run(line)
            r.font.size = Pt(9)
            r.bold = k == 0
    return t


def acting_on(party):
    """«, действующего на основании X» — или ничего, если основание не указываем.

    Полномочия даёт сама доверенность, а не строка в преамбуле: неверное или
    отсутствующее указание основания сделку не порочит (Пленум ВС № 25 от
    23.06.2015). Поэтому допустимо оставить `acting_on` пустым — но тогда
    копию доверенности нужно забрать себе в дело.
    """
    v = (party.get("acting_on") or "").strip()
    return f", действующего на основании {v}" if v else ""


