def register_fonts() -> None:
    pdfmetrics.registerFont(TTFont("Onest", str(FONTS / "Onest-Regular.ttf")))
    pdfmetrics.registerFont(TTFont("Onest-Semi", str(FONTS / "Onest-SemiBold.ttf")))
    pdfmetrics.registerFont(TTFont("Onest-Bold", str(FONTS / "Onest-Bold.ttf")))


def styles() -> dict:
    def st(name, **kw):
        base = dict(fontName="Onest", fontSize=9.5, leading=13.5, textColor=INK,
                    alignment=TA_LEFT)
        base.update(kw)
        return ParagraphStyle(name, **base)

    return {
        "h1": st("h1", fontName="Onest-Bold", fontSize=19, leading=23, spaceAfter=3),
        "sub": st("sub", fontSize=10, leading=14, textColor=MUTED, spaceAfter=13),
        "h2": st("h2", fontName="Onest-Bold", fontSize=12.5, leading=16,
                 spaceBefore=9, spaceAfter=4),
        "p": st("p", spaceAfter=4),
        "small": st("small", fontSize=8.3, leading=11.5, textColor=MUTED, spaceAfter=4),
        "cell": st("cell", fontSize=9, leading=12),
        "cellb": st("cellb", fontName="Onest-Semi", fontSize=9, leading=12),
        "cellm": st("cellm", fontSize=8.6, leading=11.5, textColor=MUTED),
        "cellnum": st("cellnum", fontSize=8.4, leading=11.5),
        "itemh": st("itemh", fontName="Onest-Semi", fontSize=10, leading=13.5,
                    spaceAfter=2),
        "item": st("item", fontSize=9.2, leading=12.4, spaceAfter=2),
        "fix": st("fix", fontSize=9.2, leading=12.4, textColor=BLUE),
        "link": st("link", fontSize=8.6, leading=11.5, textColor=BLUE),
    }


def logo_chip(height_px: int = 240) -> ImageReader:
    im = Image.open(LOGO).convert("RGBA")
    w = round(im.width * height_px / im.height)
    im = im.resize((w, height_px), Image.LANCZOS)
    mask = Image.new("L", im.size, 0)
    ImageDraw.Draw(mask).rounded_rectangle([0, 0, im.width - 1, im.height - 1],
                                           radius=round(height_px * 0.16), fill=255)
    im.putalpha(mask)
    return ImageReader(im)


def chip_png(height_px: int = 240) -> Path:
    out = HERE / "out" / "_ff-chip.png"
    out.parent.mkdir(parents=True, exist_ok=True)
    if not out.exists():
        Image.open(LOGO)  # чтобы упасть понятно, если файла нет
        logo_chip(height_px)._image.save(out)  # noqa: SLF001
    return out


def nbsp(text: str) -> str:
    text = re.sub(r"(?<=\d) (?=\d{3}\b)", " ", text)
    return re.sub(r"(?<=\d) (?=₽)", " ", text)


def diff_table(s) -> Table:
    head = ["Реквизит", "Договор 1", "Договор 2", "Как правильно"]
    data = [[Paragraph(f"<b>{h}</b>", s["cellb"]) for h in head]]
    for name, a, b, verdict in DIFFS:
        data.append([
            Paragraph(name, s["cellb"]),
            Paragraph(a.replace("\n", "<br/>"), s["cellnum"]),
            Paragraph(b.replace("\n", "<br/>"), s["cellnum"]),
            Paragraph(verdict.replace("\n", "<br/>"), s["cellm"]),
        ])
    t = Table(data, colWidths=[26 * mm, 45 * mm, 46 * mm, 45 * mm],
              repeatRows=1, hAlign="LEFT")
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), HEAD_BG),
        ("LINEBELOW", (0, 0), (-1, 0), 0.8, BLUE),
        ("GRID", (0, 1), (-1, -1), 0.25, LINE),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
        ("LEFTPADDING", (0, 0), (-1, -1), 6),
    ]))
    return t


def issue(n: int, title: str, body: str, fix: str, s, bg, edge) -> KeepTogether:
    """Карточка одной находки: номер, суть, что делать."""
    inner = [
        Paragraph(f"{n}. {title}", s["itemh"]),
        Paragraph(body, s["item"]),
        Paragraph(f"<b>Что сделать:</b> {fix}", s["fix"]),
    ]
    t = Table([[inner]], colWidths=[162 * mm], hAlign="LEFT")
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), bg),
        ("LINEBEFORE", (0, 0), (0, -1), 2.2, edge),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
        ("LEFTPADDING", (0, 0), (-1, -1), 8),
        ("RIGHTPADDING", (0, 0), (-1, -1), 8),
    ]))
    return KeepTogether([t, Spacer(1, 4)])


def scenario(n: int, claim: str, basis: str, fix: str, s) -> KeepTogether:
    """Карточка сценария: претензия пациента, её основание и ответ новой редакции."""
    inner = [
        Paragraph(f"{n}. {claim}", s["itemh"]),
        Paragraph(f"<b>На что сошлётся:</b> {basis}", s["item"]),
        Paragraph(f"<b>В новой редакции:</b> {fix}", s["fix"]),
    ]
    t = Table([[inner]], colWidths=[162 * mm], hAlign="LEFT")
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#F4F7FA")),
        ("LINEBEFORE", (0, 0), (0, -1), 2.2, BLUE),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
        ("LEFTPADDING", (0, 0), (-1, -1), 8),
        ("RIGHTPADDING", (0, 0), (-1, -1), 8),
    ]))
    return KeepTogether([t, Spacer(1, 4)])


