"""Рабочие бланки, которые нужны, когда что-то пошло не по плану.

Зачем каждый из них:

· Акт осмотра результата оказанной услуги — п. 8.5 договора прямо требует
  дать Исполнителю осмотреть работу до её переделки третьими лицами, а
  п. 6.6 — обратиться для осмотра при недостатке в гарантийный срок. Без
  акта осмотра клиника в споре не может доказать, в каком состоянии была
  работа и по чьей вине возник недостаток.
· Ответ на обращение (претензию) — требования потребителя об уменьшении
  цены, возмещении расходов и возврате денег удовлетворяются в течение
  10 дней (ст. 31 Закона РФ «О защите прав потребителей»). Молчание
  клиники — это неустойка 3 % за каждый день (ст. 28) и штраф 50 % от
  присуждённого (ч. 6 ст. 13). Ответ по форме и в срок снимает половину
  риска ещё до суда.
· Журнал учёта обращений — доказательство даты получения и даты ответа.
  В суде спор часто идёт именно о том, обращался ли пациент и когда.
· Уведомление пациенту — фиксирует даты, от которых считаются сроки:
  готовность конструкции (хранение 6 месяцев, п. 2.9 договора),
  приостановление лечения при неоплате (п. 4.9), вызов на контрольный
  осмотр (условие действия гарантии, п. 6.3).
· Заявление о выдаче медицинских документов — пациент вправе знакомиться
  с документацией и получать копии (ч. 4 и 5 ст. 22 Федерального закона
  № 323-ФЗ, приказ Минздрава России от 12.11.2021 № 1050н), а для вычета
  ему выдаются копия договора и справка об оплате (п. 32 Правил № 659).
  Письменное заявление — единственное законное основание выдать документы
  и защита от выдачи данных постороннему.
· Лист учёта дозовых нагрузок — доза, полученная пациентом при
  рентгенологическом исследовании, подлежит регистрации, а гражданин
  вправе получить информацию о ней (ст. 17 Федерального закона от
  09.01.1996 № 3-ФЗ «О радиационной безопасности населения»). Лист
  вклеивается в медицинскую карту.
"""
