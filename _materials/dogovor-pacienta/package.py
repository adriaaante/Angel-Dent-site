def build_kits(target: Path) -> list[str]:
    """Склеивает комплекты из pdf-двойников. Без pymupdf просто пропускаем."""
    try:
        import pymupdf
    except ImportError:
        print("  · комплекты не собраны: нет pymupdf")
        return []
    target.mkdir(parents=True, exist_ok=True)
    made = []
    for title, files in KITS:
        doc = pymupdf.open()
        for f in files:
            src = OUT / f"{f}.pdf"
            if not src.exists():
                print(f"  ⚠ нет {src.name} — комплект «{title}» неполный")
                continue
            with pymupdf.open(src) as part:
                doc.insert_pdf(part)
        doc.save(target / f"{title}.pdf")
        doc.close()
        made.append(title)
    return made


def publish(root: Path) -> None:
    """Копия пакета на сайт клиники: angel-denta.ru/dokumenty/ за PIN-кодом.

    Папка `dokumenty/files/` закрыта .htaccess и отдаётся только через
    `file.php` после входа, поэтому прямых ссылок на бланки не существует.
    Сюда кладётся то же, что и в архив, плюс сам архив и веб-версия страницы.
    """
    if not WEB.exists():
        print("  · сайт не найден — публикация пропущена")
        return
    files = WEB / "files"
    for old in files.iterdir():
        if old.name != ".htaccess":
            shutil.rmtree(old) if old.is_dir() else old.unlink()
    for item in root.iterdir():
        if item.name == "Документы-клиники.html":
            continue
        if item.is_dir():
            shutil.copytree(item, files / item.name)
        else:
            shutil.copy2(item, files / item.name)
    shutil.copy2(ZIP, files / ZIP.name)
    (files / "page.html").write_text(page("web"), encoding="utf-8")
    total = sum(p.stat().st_size for p in files.rglob("*") if p.is_file())
    print(f"  ✓ страница на сайт: dokumenty/ (PIN, {total // 1024 // 1024} МБ)")


def main() -> None:
    known = {d[0] for d in DOCS}
    have = {p.stem for p in OUT.glob("*.docx")}
    if known != have:
        for f in sorted(have - known):
            print(f"  ⚠ бланк не описан в DOCS: {f}")
        for f in sorted(known - have):
            print(f"  ⚠ в DOCS есть, но файла нет: {f}")
        sys.exit(1)

    if PKG.exists():
        shutil.rmtree(PKG)
    root = PKG / "Документы-клиники"
    for file, sect, *_ in DOCS:
        dst = root / sect
        dst.mkdir(parents=True, exist_ok=True)
        shutil.copy2(OUT / f"{file}.docx", dst / f"{file}.docx")

    kits = build_kits(root / "Комплекты для печати")
    # В архиве кнопки «скачать весь архив» быть не может — он сам и есть архив.
